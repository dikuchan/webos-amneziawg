export function resolveUILanguage(
  saved: string | null,
  systemLocale: string,
): UILanguage {
  if (saved === "ru" || saved === "en") return saved;
  return /^ru(?:[-_][a-z0-9]{2,8})*$/i.test(systemLocale) ? "ru" : "en";
}

export function formatTraffic(
  value: number | null,
  language: UILanguage,
): string {
  if (value === null) return "—";
  const units =
    language === "ru"
      ? ["Б", "КБ", "МБ", "ГБ", "ТБ", "ПБ"]
      : ["B", "KB", "MB", "GB", "TB", "PB"];
  let amount = value;
  let unit = 0;
  while (amount >= 1024 && unit < units.length - 1) {
    amount /= 1024;
    unit++;
  }
  const formatter = new Intl.NumberFormat(
    language === "ru" ? "ru-RU" : "en-US",
    {
      minimumFractionDigits: unit === 0 ? 0 : 1,
      maximumFractionDigits: unit === 0 ? 0 : 1,
      useGrouping: false,
    },
  );
  const label = units[unit];
  if (label === undefined) throw new Error("Invalid traffic unit");
  return formatter.format(amount) + " " + label;
}
